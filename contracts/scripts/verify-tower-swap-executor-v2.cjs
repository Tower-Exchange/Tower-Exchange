const fs = require("fs");
const path = require("path");
const hre = require("hardhat");
const { verifyOnArcscan } = require("./lib/verifyOnArcscan.cjs");

function readJson(filePath) {
  return fs.existsSync(filePath)
    ? JSON.parse(fs.readFileSync(filePath, "utf8"))
    : null;
}

async function main() {
  const deploymentFile = path.join(
    __dirname,
    "..",
    "deployments",
    `tower-swap-executor-v2-${hre.network.name}-deployment.json`,
  );
  const saved = readJson(deploymentFile);
  const address = process.env.TOWER_SWAP_EXECUTOR_V2_ADDRESS || saved?.executor;
  const treasury = saved?.treasury || process.env.TOWER_SWAP_EXECUTOR_TREASURY;
  const owner = saved?.owner || process.env.OWNER_ADDRESS;
  const feeBps = Number(
    saved?.feeBps || process.env.TOWER_SWAP_EXECUTOR_FEE_BPS || "30",
  );

  if (!address || !treasury || !owner) {
    throw new Error(
      "Set TOWER_SWAP_EXECUTOR_V2_ADDRESS, TOWER_SWAP_EXECUTOR_TREASURY, and OWNER_ADDRESS, or keep the V2 deployment JSON generated by the deploy script.",
    );
  }

  const status = await verifyOnArcscan(hre, {
    address,
    constructorArguments: [treasury, owner, feeBps],
    contract: "contracts/TowerSwapExecutorV2.sol:TowerSwapExecutorV2",
    label: "TowerSwapExecutorV2",
    license: "MIT",
  });

  if (saved) {
    fs.writeFileSync(
      deploymentFile,
      JSON.stringify({ ...saved, verificationStatus: status }, null, 2),
    );
  }

  console.log("Verification status:", status);
  if (status !== "verified" && status !== "skipped") process.exitCode = 1;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
